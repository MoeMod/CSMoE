#pragma once

#define ADD_NAMED_ARGUMENT(Z, I, ARGSTYPE_TUPLE) typename TypeIdentity<BOOST_PP_TUPLE_ELEM(I, ARGSTYPE_TUPLE)>::type BOOST_PP_CAT(x, BOOST_PP_DEC(I))
#define NAMED_ARGUMENT(SIZE, ...) BOOST_PP_IF(BOOST_PP_EQUAL(SIZE, 1), (), (BOOST_PP_ENUM_SHIFTED(SIZE, ADD_NAMED_ARGUMENT, (__VA_ARGS__)))) 
#define NAMED_ARGUMENT_THIS(THISCLASS, SIZE, ...) BOOST_PP_IF(BOOST_PP_EQUAL(SIZE, 1), (THISCLASS *that), (THISCLASS *that, BOOST_PP_ENUM_SHIFTED(SIZE, ADD_NAMED_ARGUMENT, (__VA_ARGS__)))) 